const assert=require('node:assert/strict');
const fs=require('node:fs');
const js=fs.readFileSync('tools/gm_v47_runtime.js','utf8');
const css=fs.readFileSync('tools/bos_folio_v47.css','utf8');
const start=js.indexOf('function gmV47Tick(input){');
const end=js.indexOf('function addContents(){',start);
assert(start>=0 && end>start,'Cannot find live register renderers');
const run=new Function('const selected=new Set(["spell-list"]); const esc=x=>String(x); const gmBosTocItemKey=it=>it.chapter+":"+it.id; const gmBosItemSelected=()=>true; '+js.slice(start,end)+';return {chapter:gmBosTocChapterHTML,item:gmBosTocItemHTML};')();
const one={id:'p1',chapter:'spell-list',kind:'spell',label:'Protection'};
const html=run.chapter({chapter:{id:'spell-list',num:2,title:'Spell List by Category'},continued:false,items:[one]});
assert(html.includes('data-chapter-check="spell-list"'),'Chapter selection missing');
assert(html.includes('data-gm-toc-item-select="spell-list:p1"'),'Leaf selection missing');
assert(html.includes('data-chapter-jump="spell-list"'),'Chapter jump missing');
assert(html.includes('data-gm-toc-item-open="spell-list:p1"'),'Leaf jump missing');
assert(html.includes('gmV50LeafFolio'),'Leaf folio group missing');
const chapterRow=html.slice(html.indexOf('gmV47ChapterRow'),html.indexOf('gmV47Item'));
assert(chapterRow.indexOf('data-chapter-check')<chapterRow.indexOf('gmV47ChapterNo'),'Chapter tick must precede chapter number on left');
const row=run.item(one);
const leafText=row.indexOf('gmV47ItemLink'),folio=row.indexOf('gmV50LeafFolio'),number=row.indexOf('gmV47ItemPages'),tick=row.indexOf('gmV50LeafTick');
assert(leafText>=0&&folio>leafText&&number>folio&&tick>number,'Leaf tick must be after page number at right');
assert(!row.slice(0,folio).includes('gmV47TickBox'),'No leaf checkbox before entry title');
assert(/grid-template-columns:minmax\(0,1fr\) auto!important/.test(css),'Leaf row must use text and right-hand folio');
assert(/gmV50LeafTick svg\{width:3\.35mm!important;height:3\.35mm!important/.test(css),'Leaf artwork must match chapter 3.35mm');
assert(/gmV47TickBox svg\{display:block!important;width:3\.35mm!important;height:3\.35mm!important/.test(css),'Chapter artwork 3.35mm');
assert(html.includes('fill="#632238"')&&html.includes('stroke="#d0a648"')&&html.includes('stroke="#f0ce73"'),'Oxblood and gold tick artwork must be unchanged');
assert(!/GM_INK_A4_PRINT_GUARD_V44/.test(js),'Do not merge experimental PDF logic');
console.log('PASS: chapter tick left; leaf tick to right of folio; equal-size gold/red artwork; actions preserved');
